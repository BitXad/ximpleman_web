                         WHERE p1.venta_id = t.venta_id
                         ORDER BY p1.pasaje_id ASC
                         LIMIT 1),
                        '-'
                    ) AS cliente_nombre,
                    COALESCE(
                        NULLIF(t.facturacion_documento, ''),
                        NULLIF(c.cliente_nit, ''),
                        NULLIF(c.cliente_ci, ''),
                        (SELECT NULLIF(p2.pasaje_documento, '')
