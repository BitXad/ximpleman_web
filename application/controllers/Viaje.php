    /**
     * Genera imágenes QR locales para los tokens de abordaje de una venta.
     * Devuelve un mapa [pasaje_id => URL pública]. No modifica estados ni
     * registra abordaje; únicamente prepara el QR que se imprime en el ticket.
     */
    private function generar_qr_abordaje_pasajes($detalle_pasaje)
    {
        $resultado = array();

        if (empty($detalle_pasaje) || !is_array($detalle_pasaje)) {
            return $resultado;
        }

        $this->load->library('ciqrcode');

        $directorio_relativo = 'resources/images/abordaje_qr/';
        $directorio_fisico = FCPATH.$directorio_relativo;

        if (!is_dir($directorio_fisico)) {
            @mkdir($directorio_fisico, 0755, true);
        }

        if (!is_dir($directorio_fisico) || !is_writable($directorio_fisico)) {
            log_message('error', 'No se pudo crear/escribir el directorio de QR de abordaje: '.$directorio_fisico);
            return $resultado;
        }

        foreach ($detalle_pasaje as $detalle) {
            $pasaje_id = isset($detalle['pasaje_id']) ? (int)$detalle['pasaje_id'] : 0;
            $token = isset($detalle['pasaje_qr_token']) ? trim((string)$detalle['pasaje_qr_token']) : '';

            if ($pasaje_id <= 0 || $token === '') {
                continue;
            }

            // El hash en el nombre evita reutilizar una imagen antigua si el token cambia.
            $archivo = 'pasaje_'.$pasaje_id.'_'.substr(sha1($token), 0, 12).'.png';
            $ruta_fisica = $directorio_fisico.$archivo;

            if (!is_file($ruta_fisica) || filesize($ruta_fisica) === 0) {
                $params = array();
                $params['data'] = $token;
                $params['level'] = 'H';
                $params['size'] = 5;
                $params['savename'] = $ruta_fisica;

                try {
                    $this->ciqrcode->generate($params);
                } catch (Exception $ex) {
                    log_message('error', 'Error generando QR de abordaje para pasaje '.$pasaje_id.': '.$ex->getMessage());
                    continue;
                }
            }

            if (is_file($ruta_fisica) && filesize($ruta_fisica) > 0) {
                $resultado[$pasaje_id] = base_url($directorio_relativo.$archivo);
            }
        }

        return $resultado;
    }

