            redirect('viaje/index');
            return;
        }

        $this->Viaje_model->delete_viaje($viaje_id);
        $this->session->set_flashdata('alert_msg', '<div class="alert alert-success text-center">Viaje eliminado correctamente.</div>');
        redirect('viaje/index');
    }
