    public function generar_pasajes($viaje_id, $vehiculo_id)
    {
        if (empty($viaje_id) || empty($vehiculo_id)) {
            return array(
                'status'  => false,
                'mensaje' => 'Parámetros inválidos'
            );
        }

        $this->db->where('vehiculo_id',$vehiculo_id);
        if($this->db->field_exists('asiento_es_vendible','asientos')) $this->db->where('asiento_es_vendible',1);
        if($this->db->field_exists('asiento_mostrar','asientos')) $this->db->where('asiento_mostrar',1);
        if($this->db->field_exists('asiento_tipo_elemento','asientos')) $this->db->where_in('asiento_tipo_elemento',array('ASIENTO_NORMAL','CAMA','LEITO'));
        $asientos=$this->db->order_by('nivel_id','ASC')->order_by('asiento_y','ASC')->order_by('asiento_x','ASC')->order_by('asiento_orden','ASC')->get('asientos')->result();

        if (!$asientos) {
            return array(
                'status'  => false,
                'mensaje' => 'No se encontraron asientos para el vehículo'
            );
        }

        $insertados = 0;
        $existentes = 0;

        $this->db->trans_begin();

        foreach ($asientos as $asiento) {

            $existe = $this->db
                ->where('viaje_id', $viaje_id)
                ->where('asiento_id', $asiento->asiento_id)
                ->get('pasaje')
                ->row();

            if ($existe) {
                $existentes++;
                continue;
            }

            $data = array(
                'asiento_id'      => $asiento->asiento_id,
                'viaje_id'        => $viaje_id,
                'pasaje_numero'   => $asiento->asiento_numero,
                'pasaje_precio'   => ($asiento->asiento_precio !== null) ? (float)$asiento->asiento_precio : 0,
                'estado_id'       => 50,
                'pasaje_fecha'    => date('Y-m-d'),
                'pasaje_hora'     => date('H:i:s'),
                'usuario_id'      => $this->session->userdata('usuario_id') ? $this->session->userdata('usuario_id') : null
            );

            if($this->db->table_exists('ruta_parada')){$vr=$this->db->query("SELECT ruta_id FROM viaje WHERE viaje_id=? LIMIT 1",array($viaje_id))->row_array();if($vr){$ro=$this->db->query("SELECT * FROM ruta_parada WHERE ruta_id=? AND rutaparada_tipo='ORIGEN' AND estado_id=1 ORDER BY rutaparada_orden LIMIT 1",array($vr['ruta_id']))->row_array();$rd=$this->db->query("SELECT * FROM ruta_parada WHERE ruta_id=? AND rutaparada_tipo='DESTINO' AND estado_id=1 ORDER BY rutaparada_orden DESC LIMIT 1",array($vr['ruta_id']))->row_array();if($ro&&$rd){$data['rutaparada_origen_id']=$ro['rutaparada_id'];$data['rutaparada_destino_id']=$rd['rutaparada_id'];$data['pasaje_tramo_origen_orden']=$ro['rutaparada_orden'];$data['pasaje_tramo_destino_orden']=$rd['rutaparada_orden'];$data['pasaje_origen']=$ro['rutaparada_nombre'];$data['pasaje_destino']=$rd['rutaparada_nombre'];}}}$this->db->insert('pasaje',$data);if($this->db->table_exists('viaje_asiento_lock'))$this->db->query("INSERT IGNORE INTO viaje_asiento_lock(viaje_id,asiento_id,lock_actualizado) VALUES(?,?,NOW())",array($viaje_id,$asiento->asiento_id));$insertados++;
        }

        if ($this->db->trans_status() === false) {
            $this->db->trans_rollback();
            return array(
                'status'  => false,
                'mensaje' => 'Ocurrió un error al generar los pasajes'
            );
        }

        $this->db->trans_commit();

        return array(
            'status'     => true,
            'mensaje'    => 'Pasajes generados correctamente',
            'insertados' => $insertados,
            'existentes' => $existentes
        );
    }    
    
