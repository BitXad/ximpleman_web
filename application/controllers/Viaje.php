     * Cambia el estado del viaje respetando la máquina de estados y deja bitácora.
     */
    public function cambiar_estado($viaje_id)
    {
        $viaje_id = (int)$viaje_id;
        $estado_nuevo = (int)$this->input->post('estado_id');
        $motivo = trim((string)$this->input->post('motivo'));
        $usuario_id = (int)$this->session_data['usuario_id'];

        $this->db->trans_begin();
        try {
            $viaje = $this->db->query(
                "SELECT viaje_id, estado_id FROM viaje WHERE viaje_id = ? FOR UPDATE",
                array($viaje_id)
            )->row_array();

            if (!$viaje) {
                throw new Exception('El viaje no existe.');
            }

            $estado_actual = (int)$viaje['estado_id'];
            if (!$this->Viaje_model->puede_transicionar($estado_actual, $estado_nuevo)) {
                throw new Exception('La transición de estado solicitada no está permitida.');
            }

            if ($estado_nuevo === 62) {
                throw new Exception('El estado CERRADO solo puede aplicarse mediante la función CERRAR VIAJE, que realiza el arqueo y la confirmación previa.');
            }
            if ($estado_nuevo === 63) {
                throw new Exception('El estado CANCELADO solo puede aplicarse mediante la función CANCELAR VIAJE, que identifica y registra a todos los pasajeros afectados.');
            }

            if (in_array($estado_nuevo, array(63,64,65), true) && $motivo === '') {
                throw new Exception('Debe registrar un motivo para cancelar, reprogramar o suspender el viaje.');
            }

            $this->db->where('viaje_id', $viaje_id);
            if (!$this->db->update('viaje', array('estado_id' => $estado_nuevo))) {
                throw new Exception('No fue posible actualizar el estado del viaje.');
            }

            if (!$this->Viaje_model->registrar_historial_estado($viaje_id, $estado_actual, $estado_nuevo, $usuario_id, $motivo)) {
                throw new Exception('No fue posible registrar la bitácora del cambio de estado.');
            }

            if ($this->db->trans_status() === false) {
                throw new Exception('La base de datos rechazó el cambio de estado.');
            }

            $this->db->trans_commit();
            $this->session->set_flashdata('alert_msg', '<div class="alert alert-success text-center">Estado del viaje actualizado correctamente.</div>');
        } catch (Exception $e) {
            $this->db->trans_rollback();
            $this->session->set_flashdata('alert_msg', '<div class="alert alert-danger text-center">'.htmlspecialchars($e->getMessage(), ENT_QUOTES, 'UTF-8').'</div>');
        }
        redirect('viaje/index');
    }

