    private function _guardar_tripulacion_viaje($viaje_id)
    {
        if (!$this->db->table_exists('viaje_conductor')) return true;
        $conductores = $this->input->post('tripulacion_conductor_id');
        $roles = $this->input->post('tripulacion_rol');
        $horas_inicio = $this->input->post('tripulacion_hora_inicio');
        $horas_fin = $this->input->post('tripulacion_hora_fin');
        $observaciones = $this->input->post('tripulacion_observacion');
        $conductores = is_array($conductores) ? $conductores : array();
        $roles = is_array($roles) ? $roles : array();
        $horas_inicio = is_array($horas_inicio) ? $horas_inicio : array();
        $horas_fin = is_array($horas_fin) ? $horas_fin : array();
        $observaciones = is_array($observaciones) ? $observaciones : array();

        $this->db->where('viaje_id', (int)$viaje_id)->delete('viaje_conductor');
        if ($this->db->trans_status() === FALSE) return false;
        $orden = 1;
        foreach ($conductores as $i => $conductor_id) {
            $conductor_id = (int)$conductor_id;
            if ($conductor_id <= 0) continue;
            $rol = strtoupper(trim(isset($roles[$i]) ? $roles[$i] : 'RELEVO'));
            if (!in_array($rol, array('PRINCIPAL','SEGUNDO','RELEVO','AYUDANTE'), true)) $rol = 'RELEVO';
            $fila = array('viaje_id'=>(int)$viaje_id, 'conductor_id'=>$conductor_id);
            if ($this->db->field_exists('viaje_conductor_rol','viaje_conductor')) $fila['viaje_conductor_rol']=$rol;
            if ($this->db->field_exists('viaje_conductor_hora_inicio','viaje_conductor')) $fila['viaje_conductor_hora_inicio']=!empty($horas_inicio[$i])?$horas_inicio[$i]:null;
            if ($this->db->field_exists('viaje_conductor_hora_fin','viaje_conductor')) $fila['viaje_conductor_hora_fin']=!empty($horas_fin[$i])?$horas_fin[$i]:null;
            if ($this->db->field_exists('viaje_conductor_observacion','viaje_conductor')) $fila['viaje_conductor_observacion']=isset($observaciones[$i])?trim($observaciones[$i]):'';
            if ($this->db->field_exists('viaje_conductor_orden','viaje_conductor')) $fila['viaje_conductor_orden']=$orden;
            if ($this->db->field_exists('estado_id','viaje_conductor')) $fila['estado_id']=1;
            if ($this->db->field_exists('viajeconductor_fecha','viaje_conductor')) $fila['viajeconductor_fecha']=date('Y-m-d');
            if ($this->db->field_exists('viajeconductor_hora','viaje_conductor')) $fila['viajeconductor_hora']=date('H:i:s');
            if (!$this->db->insert('viaje_conductor',$fila)) return false;
            $orden++;
        }
        return true;
    }

