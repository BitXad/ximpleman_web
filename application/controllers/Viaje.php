    public function cambiar_asiento() {
        $pasaje_origen = (int)$this->input->post("pasaje_origen");
        $pasaje_destino = (int)$this->input->post("pasaje_destino");
        $motivo = trim((string)$this->input->post("motivo"));
        $usuario_id = isset($this->session_data['usuario_id']) ? (int)$this->session_data['usuario_id'] : 0;

        $response = array('ok' => false, 'mensaje' => 'No fue posible realizar el cambio de asiento.');
        $this->output->set_content_type('application/json');

        if (!$this->Viaje_model->usuario_tiene_rol($usuario_id, 208)) {
            $response['mensaje'] = 'No tiene permiso para cambiar asientos.';
            echo json_encode($response);
            return;
        }
        if ($pasaje_origen <= 0 || $pasaje_destino <= 0 || $pasaje_origen === $pasaje_destino) {
            $response['mensaje'] = 'Debe seleccionar un asiento destino diferente al asiento actual.';
            echo json_encode($response);
            return;
        }
        if ($motivo === '') {
            $response['mensaje'] = 'El motivo del cambio de asiento es obligatorio.';
            echo json_encode($response);
            return;
        }

        $this->db->trans_begin();
        try {
            // Bloquear ambos registros para impedir que otro operador tome el asiento destino.
            $pasaje = $this->db->query(
                "SELECT p.*, a.asiento_numero, a.asiento_descripcion
                 FROM pasaje p
                 INNER JOIN asientos a ON a.asiento_id = p.asiento_id
                 WHERE p.pasaje_id = ? FOR UPDATE",
                array($pasaje_origen)
            )->row_array();
            $destino = $this->db->query(
                "SELECT p.*, a.asiento_numero, a.asiento_descripcion
                 FROM pasaje p
                 INNER JOIN asientos a ON a.asiento_id = p.asiento_id
                 WHERE p.pasaje_id = ? FOR UPDATE",
                array($pasaje_destino)
            )->row_array();

            if (!$pasaje || !$destino || (int)$pasaje['viaje_id'] !== (int)$destino['viaje_id']) {
                throw new Exception('Los asientos no pertenecen al mismo viaje.');
            }
            if (!in_array((int)$pasaje['estado_id'], array(52, 54), true)) {
                throw new Exception('El pasaje origen ya no se encuentra reservado o vendido.');
            }

            $viaje = $this->db->query(
                "SELECT viaje_id, estado_id FROM viaje WHERE viaje_id = ? FOR UPDATE",
                array((int)$pasaje['viaje_id'])
            )->row_array();
            if (!$viaje || !$this->Viaje_model->estado_permite_cambio_asiento((int)$viaje['estado_id'])) {
                throw new Exception('El cambio de asiento no está permitido en el estado actual del viaje.');
            }
            if ((int)$destino['estado_id'] !== 50 || (int)$destino['venta_id'] > 0) {
                throw new Exception('El asiento destino ya no está disponible. Actualice el mapa e intente nuevamente.');
            }

            $precio_origen = round((float)$pasaje['pasaje_precio'], 2);
            $precio_destino_referencia = round((float)$destino['pasaje_precio'], 2);
            $diferencia_precio = round($precio_destino_referencia - $precio_origen, 2);

            // Historial ANTES de modificar los asientos. La tarifa cobrada se conserva:
            // la diferencia queda auditada como referencia y no altera silenciosamente la venta/pago original.
            $historial = array(
                'viaje_id' => (int)$pasaje['viaje_id'],
                'venta_id' => (int)$pasaje['venta_id'],
                'pasaje_origen_id' => (int)$pasaje['pasaje_id'],
                'pasaje_destino_id' => (int)$destino['pasaje_id'],
                'asiento_anterior_id' => (int)$pasaje['asiento_id'],
                'asiento_anterior' => (string)$pasaje['asiento_numero'],
                'asiento_nuevo_id' => (int)$destino['asiento_id'],
                'asiento_nuevo' => (string)$destino['asiento_numero'],
                'precio_anterior' => $precio_origen,
                'precio_nuevo_referencia' => $precio_destino_referencia,
                'diferencia_precio' => $diferencia_precio,
                'usuario_id' => $usuario_id,
                'cambio_fecha' => date('Y-m-d'),
                'cambio_hora' => date('H:i:s'),
                'cambio_fechahora' => date('Y-m-d H:i:s'),
                'cambio_motivo' => $motivo,
                'estado_pasaje_id' => (int)$pasaje['estado_id']
            );
            if (!$this->db->insert('pasaje_cambio_asiento', $historial)) {
                throw new Exception('No fue posible registrar la auditoría del cambio de asiento.');
            }
            $cambio_id = (int)$this->db->insert_id();

            // Limpiar el asiento anterior, conservando únicamente los datos estructurales del asiento/viaje.
            $limpiar = array(
                'factura_id' => 0,
                'cliente_id' => 0,
                'pasaje_nombre' => '',
                'pasaje_telefono' => '',
                'pasaje_documento' => '',
                'estado_id' => 50,
                'usuario_id' => 0,
                'venta_id' => 0,
                'cdi_codigoclasificador' => 0,
                'pasaje_fecha' => null,
                'pasaje_hora' => null,
                'pasaje_fechareserva' => null,
                'pasaje_fechalimiteres' => null,
                'pasaje_horalimiteres' => null,
                'pasaje_tieneequipaje' => 0,
                'pasaje_detalleequipaje' => null,
                'pasaje_fechahoraequipaje' => null,
                'pasaje_controlabordaje' => null,
                'pasaje_bloqueado_hasta' => null
            );
            if (!$this->db->where('pasaje_id', $pasaje_origen)->update('pasaje', $limpiar)) {
                throw new Exception('No fue posible liberar el asiento anterior.');
            }

            // Mover la asignación completa. Se conserva el precio efectivamente vendido/reservado.
            $mover = array(
                'factura_id' => $pasaje['factura_id'],
                'cliente_id' => $pasaje['cliente_id'],
                'pasaje_nombre' => $pasaje['pasaje_nombre'],
                'pasaje_telefono' => $pasaje['pasaje_telefono'],
                'pasaje_documento' => $pasaje['pasaje_documento'],
                'estado_id' => $pasaje['estado_id'],
                'usuario_id' => $pasaje['usuario_id'],
                'venta_id' => $pasaje['venta_id'],
                'cdi_codigoclasificador' => $pasaje['cdi_codigoclasificador'],
                'pasaje_precio' => $pasaje['pasaje_precio'],
                'pasaje_fecha' => $pasaje['pasaje_fecha'],
                'pasaje_hora' => $pasaje['pasaje_hora'],
                'pasaje_fechareserva' => $pasaje['pasaje_fechareserva'],
                'pasaje_fechalimiteres' => $pasaje['pasaje_fechalimiteres'],
                'pasaje_horalimiteres' => $pasaje['pasaje_horalimiteres'],
                'pasaje_tieneequipaje' => $pasaje['pasaje_tieneequipaje'],
                'pasaje_detalleequipaje' => $pasaje['pasaje_detalleequipaje'],
                'pasaje_fechahoraequipaje' => $pasaje['pasaje_fechahoraequipaje'],
                'pasaje_controlabordaje' => $pasaje['pasaje_controlabordaje'],
                'pasaje_bloqueado_hasta' => $pasaje['pasaje_bloqueado_hasta']
            );
            if (!$this->db->where('pasaje_id', $pasaje_destino)->update('pasaje', $mover)) {
                throw new Exception('No fue posible asignar el nuevo asiento.');
            }

            if ($this->db->trans_status() === false) {
                throw new Exception('No fue posible completar el cambio de asiento.');
            }
            $this->db->trans_commit();
            $this->load->model('Bitacora_transporte_model');
            $this->Bitacora_transporte_model->registrar('CAMBIO_ASIENTO','PASAJE',$pasaje_destino,array('pasaje_id'=>$pasaje_origen,'asiento_id'=>(int)$pasaje['asiento_id'],'asiento'=>$pasaje['asiento_numero']),array('pasaje_id'=>$pasaje_destino,'asiento_id'=>(int)$destino['asiento_id'],'asiento'=>$destino['asiento_numero']),array('pasaje_id'=>$pasaje_destino,'venta_id'=>(int)$pasaje['venta_id'],'viaje_id'=>(int)$pasaje['viaje_id'],'usuario_id'=>$usuario_id,'observacion'=>$motivo));

            $response = array(
                'ok' => true,
                'mensaje' => 'Asiento cambiado correctamente.',
                'cambio_id' => $cambio_id,
                'asiento_anterior' => $pasaje['asiento_numero'],
                'asiento_nuevo' => $destino['asiento_numero'],
                'precio_anterior' => $precio_origen,
                'precio_nuevo_referencia' => $precio_destino_referencia,
                'diferencia_precio' => $diferencia_precio
            );
            echo json_encode($response);
        } catch (Exception $e) {
            if ($this->db->trans_status() !== false || $this->db->trans_status() === false) {
                $this->db->trans_rollback();
            }
            $response['mensaje'] = $e->getMessage();
            echo json_encode($response);
        }
    }
   

