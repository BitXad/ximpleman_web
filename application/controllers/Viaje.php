    /** Cancela toda la salida en una sola transacción y conserva las ventas originales. */
    public function procesar_cancelacion($viaje_id)
    {
        $usuario_id=(int)$this->session_data['usuario_id'];
        if(!$this->Viaje_model->usuario_tiene_rol($usuario_id,210)) show_error('No autorizado.',403);
        $causa=trim((string)$this->input->post('causa'));
        if($causa==='') { $this->session->set_flashdata('alert_msg','<div class="alert alert-danger">La causa de cancelación es obligatoria.</div>'); redirect('viaje/cancelacion/'.$viaje_id); }

        $this->db->trans_begin();
        try {
            $viaje=$this->db->query("SELECT * FROM viaje WHERE viaje_id=? FOR UPDATE",array((int)$viaje_id))->row_array();
            if(!$viaje) throw new Exception('El viaje no existe.');
            if(in_array((int)$viaje['estado_id'],array(58,60,63),true)) throw new Exception('El viaje ya no puede cancelarse desde este proceso.');

            $existente=$this->db->query("SELECT cancelacion_id FROM viaje_cancelacion WHERE viaje_id=? AND cancelacion_estado='ACTIVA' LIMIT 1 FOR UPDATE",array((int)$viaje_id))->row_array();
            if($existente) throw new Exception('El viaje ya tiene una cancelación activa.');

            $pasajes=$this->db->query("SELECT p.*,a.asiento_numero,IFNULL(vp.forma_id,0) forma_id_original,fp.forma_nombre,
                                             IFNULL(vp.venta_total,0) venta_total,IFNULL(vp.venta_acuentareserva,0) venta_acuentareserva
                                      FROM pasaje p
                                      LEFT JOIN asientos a ON a.asiento_id=p.asiento_id
                                      LEFT JOIN venta_pasaje vp ON vp.venta_id=p.venta_id
                                      LEFT JOIN forma_pago fp ON fp.forma_id=vp.forma_id
                                      WHERE p.viaje_id=? AND p.estado_id IN (52,54) FOR UPDATE",array((int)$viaje_id))->result_array();
            $total=0; foreach($pasajes as $pp) $total += (float)$pp['pasaje_precio'];

            $cab=array('viaje_id'=>(int)$viaje_id,'usuario_id'=>$usuario_id,'cancelacion_fecha'=>date('Y-m-d'),'cancelacion_hora'=>date('H:i:s'),
                       'cancelacion_fechahora'=>date('Y-m-d H:i:s'),'cancelacion_causa'=>$causa,'cancelacion_estado'=>'ACTIVA',
                       'estado_viaje_anterior'=>(int)$viaje['estado_id'],'cantidad_afectados'=>count($pasajes),'monto_referencia'=>$total);
            if(!$this->db->insert('viaje_cancelacion',$cab)) throw new Exception('No fue posible registrar la cancelación.');
            $cancelacion_id=(int)$this->db->insert_id();

            foreach($pasajes as $pp){
                $importe=(float)$pp['pasaje_precio'];
                if((int)$pp['estado_id']===52 && (float)$pp['venta_acuentareserva']>0){
                    $n=max(1,(int)$this->db->where('venta_id',(int)$pp['venta_id'])->where_in('estado_id',array(52,66))->count_all_results('pasaje'));
                    $importe=(float)$pp['venta_acuentareserva']/$n;
                }
                $det=array('cancelacion_id'=>$cancelacion_id,'pasaje_id_original'=>(int)$pp['pasaje_id'],'venta_id'=>(int)$pp['venta_id'],
                           'asiento_id_original'=>(int)$pp['asiento_id'],'asiento_numero'=>$pp['asiento_numero'],'pasajero_nombre'=>$pp['pasaje_nombre'],
                           'pasajero_documento'=>$pp['pasaje_documento'],'pasajero_telefono'=>$pp['pasaje_telefono'],'estado_pasaje_original'=>(int)$pp['estado_id'],
                           'forma_id_original'=>(int)$pp['forma_id_original'],'importe_pagado'=>$importe,'devolucion_sugerida'=>$importe,'gestion_estado'=>'PENDIENTE',
                           'detalle_snapshot'=>json_encode($pp,JSON_UNESCAPED_UNICODE));
                if(!$this->db->insert('viaje_cancelacion_detalle',$det)) throw new Exception('No fue posible guardar el detalle de pasajeros afectados.');
                if(!$this->db->where('pasaje_id',(int)$pp['pasaje_id'])->update('pasaje',array('estado_id'=>66,'pasaje_cancelacion_id'=>$cancelacion_id))) throw new Exception('No fue posible marcar los pasajes afectados.');
            }

            if(!$this->db->where('viaje_id',(int)$viaje_id)->update('viaje',array('estado_id'=>63))) throw new Exception('No fue posible bloquear el viaje cancelado.');
            if(!$this->Viaje_model->registrar_historial_estado((int)$viaje_id,(int)$viaje['estado_id'],63,$usuario_id,'CANCELACIÓN TOTAL: '.$causa)) throw new Exception('No fue posible registrar la bitácora.');
            if($this->db->trans_status()===false) throw new Exception('La base de datos rechazó la cancelación.');
            $this->db->trans_commit();
            $this->session->set_flashdata('alert_msg','<div class="alert alert-success"><b>Viaje cancelado.</b> Las ventas quedaron bloqueadas y los pasajeros fueron marcados para gestión.</div>');
        }catch(Exception $e){ $this->db->trans_rollback(); $this->session->set_flashdata('alert_msg','<div class="alert alert-danger">'.$e->getMessage().'</div>'); }
        redirect('viaje/cancelacion/'.$viaje_id);
    }

    /** Reprogramación masiva de todos los pasajeros pendientes de una cancelación. */
    public function reprogramar_cancelacion_masiva($cancelacion_id)
    {
        $usuario_id=(int)$this->session_data['usuario_id'];
        if(!$this->Viaje_model->usuario_tiene_rol($usuario_id,210)) show_error('No autorizado.',403);
        $destino_id=(int)$this->input->post('viaje_destino_id');
        if($destino_id<=0){ $this->session->set_flashdata('alert_msg','<div class="alert alert-danger">Seleccione un viaje destino.</div>'); redirect('viaje/index'); }

        $cab=$this->db->get_where('viaje_cancelacion',array('cancelacion_id'=>(int)$cancelacion_id))->row_array();
        if(!$cab) show_404();
        $destino=$this->db->get_where('viaje',array('viaje_id'=>$destino_id))->row_array();
        if(!$destino || !in_array((int)$destino['estado_id'],array(61,56),true)) { $this->session->set_flashdata('alert_msg','<div class="alert alert-danger">El viaje destino no está habilitado.</div>'); redirect('viaje/cancelacion/'.$cab['viaje_id']); }
        $origen=$this->db->get_where('viaje',array('viaje_id'=>(int)$cab['viaje_id']))->row_array();
        if((int)$origen['ruta_id']!==(int)$destino['ruta_id']) { $this->session->set_flashdata('alert_msg','<div class="alert alert-danger">El viaje destino debe pertenecer a la misma ruta.</div>'); redirect('viaje/cancelacion/'.$cab['viaje_id']); }

        // Sincroniza mapa antes de abrir la transacción masiva.
        $this->generar_pasajes($destino_id,(int)$destino['vehiculo_id']);
        $this->db->trans_begin();
        try{
            $detalles=$this->db->query("SELECT * FROM viaje_cancelacion_detalle WHERE cancelacion_id=? AND gestion_estado='PENDIENTE' ORDER BY detalle_id FOR UPDATE",array((int)$cancelacion_id))->result_array();
            $libres=$this->db->query("SELECT p.*,a.asiento_numero,CASE WHEN IFNULL(p.pasaje_precio,0)>0 THEN p.pasaje_precio ELSE IFNULL(v.viaje_preciopasaje,0) END nuevo_precio
                                    FROM pasaje p INNER JOIN asientos a ON a.asiento_id=p.asiento_id INNER JOIN viaje v ON v.viaje_id=p.viaje_id
                                    WHERE p.viaje_id=? AND p.estado_id=50 AND IFNULL(p.venta_id,0)=0 ORDER BY a.asiento_numero FOR UPDATE",array($destino_id))->result_array();
            if(count($libres)<count($detalles)) throw new Exception('El viaje destino no tiene suficientes asientos libres para todos los pasajeros pendientes.');
            foreach($detalles as $i=>$d){
                $orig=$this->db->get_where('pasaje',array('pasaje_id'=>(int)$d['pasaje_id_original']))->row_array();
                if(!$orig) throw new Exception('No se encontró uno de los pasajes originales.');
                // Preferir el mismo asiento físico si está libre; si no, tomar el siguiente.
                $sel=null; foreach($libres as $k=>$l){ if((int)$l['asiento_id']===(int)$d['asiento_id_original']) { $sel=$l; unset($libres[$k]); break; } }
                if(!$sel){ $k=array_key_first($libres); $sel=$libres[$k]; unset($libres[$k]); }
                $nuevo_precio=(float)$sel['nuevo_precio']; $pagado=(float)$d['importe_pagado']; $diferencia=$nuevo_precio-$pagado;
                $gestion=$diferencia>0.009?'SALDO_PENDIENTE':($diferencia<-0.009?'DEVOLUCION_PENDIENTE':'REPROGRAMADO');
                $copiar=array('cliente_id'=>$orig['cliente_id'],'pasaje_nombre'=>$orig['pasaje_nombre'],'pasaje_telefono'=>$orig['pasaje_telefono'],'pasaje_documento'=>$orig['pasaje_documento'],
                             'cdi_codigoclasificador'=>$orig['cdi_codigoclasificador'],'venta_id'=>$orig['venta_id'],'usuario_id'=>$usuario_id,'estado_id'=>((int)$d['estado_pasaje_original']===52?52:54),
                             'pasaje_fechalimiteres'=>((int)$d['estado_pasaje_original']===52?$orig['pasaje_fechalimiteres']:null),'pasaje_horalimiteres'=>((int)$d['estado_pasaje_original']===52?$orig['pasaje_horalimiteres']:null),
                             'pasaje_fecha'=>date('Y-m-d'),'pasaje_hora'=>date('H:i:s'),'pasaje_precio'=>$nuevo_precio,'pasaje_tieneequipaje'=>$orig['pasaje_tieneequipaje'],
                             'pasaje_detalleequipaje'=>$orig['pasaje_detalleequipaje'],'pasaje_fechahoraequipaje'=>$orig['pasaje_fechahoraequipaje'],'pasaje_controlabordaje'=>null);
                if(!$this->db->where('pasaje_id',(int)$sel['pasaje_id'])->update('pasaje',$copiar)) throw new Exception('No fue posible asignar un asiento destino.');
                if(!$this->db->where('detalle_id',(int)$d['detalle_id'])->update('viaje_cancelacion_detalle',array('gestion_estado'=>$gestion,'viaje_destino_id'=>$destino_id,
                    'pasaje_destino_id'=>(int)$sel['pasaje_id'],'asiento_destino_id'=>(int)$sel['asiento_id'],'precio_destino'=>$nuevo_precio,'diferencia_precio'=>$diferencia,
                    'gestion_usuario_id'=>$usuario_id,'gestion_fechahora'=>date('Y-m-d H:i:s')))) throw new Exception('No fue posible actualizar la gestión del afectado.');
            }
            if($this->db->trans_status()===false) throw new Exception('La base de datos rechazó la reprogramación masiva.');
            $this->db->trans_commit();
            $this->session->set_flashdata('alert_msg','<div class="alert alert-success"><b>Reprogramación masiva completada.</b> Revise los saldos o devoluciones pendientes en el reporte.</div>');
        }catch(Exception $e){ $this->db->trans_rollback(); $this->session->set_flashdata('alert_msg','<div class="alert alert-danger">'.$e->getMessage().'</div>'); }
        redirect('viaje/cancelacion/'.$cab['viaje_id']);
    }

