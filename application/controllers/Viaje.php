                if($relevo_formal===null && in_array($t['rol'],array('RELEVO','SEGUNDO','SEGUNDO CONDUCTOR'))){
                    $relevo_formal=$t;
                }
            }
            // Si una instalación tiene filas antiguas sin rol, la primera y
            // segunda asignación siguen siendo utilizables como respaldo.
            if($principal_formal===null && isset($tripulacion[0])) $principal_formal=$tripulacion[0];
            if($relevo_formal===null && isset($tripulacion[1])) $relevo_formal=$tripulacion[1];

            if($principal_formal){
                $conductor=array('id'=>(int)$principal_formal['conductor_id'],'nombre'=>$principal_formal['nombre'],'licencia'=>$principal_formal['licencia'],'telefono'=>$principal_formal['telefono']);
            }
            if($relevo_formal){
                $relevo=array('id'=>(int)$relevo_formal['conductor_id'],'nombre'=>$relevo_formal['nombre'],'licencia'=>$relevo_formal['licencia'],'telefono'=>$relevo_formal['telefono']);
            }
        }

        echo json_encode(array(
            'ok'=>true,
            'viaje_id'=>(int)$r['viaje_id'],
            'vehiculo_id'=>(int)$r['vehiculo_id'],
            'vehiculo_placa'=>$r['vehiculo_placa'],
            'conductor'=>$conductor,
            'relevo'=>$relevo
        ));
    }

