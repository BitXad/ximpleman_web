            }
            if($this->db->trans_status()===false) throw new Exception('La base de datos rechazó la reprogramación.');
            $this->db->trans_commit();
            $this->load->model('Bitacora_transporte_model');
            $this->Bitacora_transporte_model->registrar('CAMBIO_VIAJE','PASAJE',$destino_id,array('pasaje_id'=>$origen_id,'viaje_id'=>(int)$origen['viaje_id'],'asiento'=>$origen['asiento_numero'],'precio'=>$precio_pagado),array('pasaje_id'=>$destino_id,'viaje_id'=>(int)$destino['viaje_id'],'asiento'=>$destino['asiento_numero'],'precio'=>$precio_nuevo,'penalidad'=>$penalidad,'ajuste'=>$ajuste_total),array('pasaje_id'=>$destino_id,'venta_id'=>(int)$origen['venta_id'],'viaje_id'=>(int)$destino['viaje_id'],'usuario_id'=>$usuario_id,'observacion'=>$motivo));
            $resp=array('ok'=>true,'mensaje'=>'Pasaje reprogramado correctamente.','reprogramacion_id'=>$reprogramacion_id,'viaje_anterior'=>(int)$origen['viaje_id'],'viaje_nuevo'=>(int)$destino['viaje_id'],'asiento_anterior'=>$origen['asiento_numero'],'asiento_nuevo'=>$destino['asiento_numero'],'precio_pagado'=>$precio_pagado,'precio_nuevo'=>$precio_nuevo,'diferencia_tarifa'=>$diferencia_tarifa,'penalidad'=>$penalidad,'ajuste_total'=>$ajuste_total,'tipo_ajuste'=>$tipo_ajuste);
        } catch(Exception $e) {
