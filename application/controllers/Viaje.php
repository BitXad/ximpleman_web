    /**
     * Reprogramación transaccional. Conserva la venta económica original y registra
     * el ajuste (cobro/saldo/devolución) como movimiento independiente y auditable.
     */
    public function reprogramar_pasaje()
    {
        $this->output->set_content_type('application/json');
        $usuario_id=isset($this->session_data['usuario_id'])?(int)$this->session_data['usuario_id']:0;
        $origen_id=(int)$this->input->post('pasaje_origen');
        $destino_id=(int)$this->input->post('pasaje_destino');
        $penalidad=round(max(0,(float)$this->input->post('penalidad')),2);
        $tipo_ajuste=strtoupper(trim((string)$this->input->post('tipo_ajuste')));
        $mantiene_forma=((int)$this->input->post('mantiene_forma_pago')===1)?1:0;
        $forma_ajuste=(int)$this->input->post('forma_id_ajuste');
        $motivo=trim((string)$this->input->post('motivo'));
        $resp=array('ok'=>false,'mensaje'=>'No fue posible reprogramar el pasaje.');
        if(!$this->Viaje_model->usuario_tiene_rol($usuario_id,209)) { $resp['mensaje']='No tiene permiso para reprogramar pasajes.'; echo json_encode($resp); return; }
        if($origen_id<=0 || $destino_id<=0 || $origen_id===$destino_id) { $resp['mensaje']='Seleccione un viaje y asiento destino válidos.'; echo json_encode($resp); return; }
        if($motivo==='') { $resp['mensaje']='El motivo de la reprogramación es obligatorio.'; echo json_encode($resp); return; }

        $this->db->trans_begin();
        try {
            $origen=$this->db->query("SELECT p.*,a.asiento_numero,a.asiento_descripcion,v.ruta_id,v.estado_id AS viaje_estado_id,v.viaje_fechasalida,v.viaje_horasalida,v.viaje_preciopasaje,r.ruta_nombre FROM pasaje p INNER JOIN asientos a ON a.asiento_id=p.asiento_id INNER JOIN viaje v ON v.viaje_id=p.viaje_id LEFT JOIN ruta r ON r.ruta_id=v.ruta_id WHERE p.pasaje_id=? FOR UPDATE",array($origen_id))->row_array();
            $destino=$this->db->query("SELECT p.*,a.asiento_numero,a.asiento_descripcion,v.ruta_id,v.estado_id AS viaje_estado_id,v.viaje_fechasalida,v.viaje_horasalida,v.viaje_preciopasaje,r.ruta_nombre FROM pasaje p INNER JOIN asientos a ON a.asiento_id=p.asiento_id INNER JOIN viaje v ON v.viaje_id=p.viaje_id LEFT JOIN ruta r ON r.ruta_id=v.ruta_id WHERE p.pasaje_id=? FOR UPDATE",array($destino_id))->row_array();
            if(!$origen || !$destino) throw new Exception('No se encontraron los pasajes origen/destino.');
            if(!in_array((int)$origen['estado_id'],array(52,54),true) || (int)$origen['venta_id']<=0) throw new Exception('El pasaje origen ya no está vendido o reservado.');
            if(!in_array((int)$origen['viaje_estado_id'],array(61,56),true)) throw new Exception('El viaje original ya no permite reprogramación.');
            if(!in_array((int)$destino['viaje_estado_id'],array(61,56),true)) throw new Exception('El viaje destino ya no permite ventas/reprogramaciones.');
            if((int)$origen['ruta_id']!==(int)$destino['ruta_id']) throw new Exception('La reprogramación solo puede realizarse a otro viaje de la misma ruta.');
            if((int)$destino['estado_id']!==50 || (int)$destino['venta_id']>0) throw new Exception('El asiento destino acaba de ser ocupado. Actualice e intente nuevamente.');

            $venta_fuente='venta_pasaje';
            $venta=$this->db->query("SELECT vp.*,fp.forma_nombre FROM venta_pasaje vp LEFT JOIN forma_pago fp ON fp.forma_id=vp.forma_id WHERE vp.venta_id=? FOR UPDATE",array((int)$origen['venta_id']))->row_array();
            if(!$venta){
                // Compatibilidad con operaciones antiguas: algunos pasajes históricos
                // quedaron vinculados a la tabla general `venta` en vez de `venta_pasaje`.
                $venta_fuente='venta';
                $venta=$this->db->query("SELECT vg.*,fp.forma_nombre FROM venta vg LEFT JOIN forma_pago fp ON fp.forma_id=vg.forma_id WHERE vg.venta_id=? FOR UPDATE",array((int)$origen['venta_id']))->row_array();
            }
            if(!$venta) throw new Exception('No se encontró la cabecera económica original del pasaje.');
            if((int)$venta['estado_id']===3) throw new Exception('La venta original está anulada.');

            $precio_pagado=round((float)$origen['pasaje_precio'],2);
            $precio_nuevo=round(((float)$destino['pasaje_precio']>0 ? (float)$destino['pasaje_precio'] : (float)$destino['viaje_preciopasaje']),2);
            if($precio_nuevo<=0) throw new Exception('El viaje destino no tiene un precio válido configurado.');
            $diferencia_tarifa=round($precio_nuevo-$precio_pagado,2);
            $ajuste_total=round($diferencia_tarifa+$penalidad,2);

            if($ajuste_total>0 && !in_array($tipo_ajuste,array('COBRAR','SALDO'),true)) throw new Exception('Debe cobrar la diferencia o generar saldo pendiente.');
            if($ajuste_total<0 && !in_array($tipo_ajuste,array('DEVOLUCION','SALDO_FAVOR'),true)) throw new Exception('Debe registrar devolución o saldo a favor.');
            if(abs($ajuste_total)<0.005) $tipo_ajuste='SIN_AJUSTE';
            $forma_original=(int)$venta['forma_id'];
            if($mantiene_forma) $forma_ajuste=$forma_original;
            if(in_array($tipo_ajuste,array('COBRAR','DEVOLUCION'),true) && $forma_ajuste<=0) throw new Exception('Seleccione la forma de pago del ajuste.');

            // Primer viaje de la cadena, aunque el pasajero ya haya sido reprogramado anteriormente.
            $prev=$this->db->query("SELECT viaje_original_id FROM pasaje_reprogramacion WHERE venta_id=? ORDER BY reprogramacion_id DESC LIMIT 1",array((int)$origen['venta_id']))->row_array();
            $viaje_original_raiz=$prev ? (int)$prev['viaje_original_id'] : (int)$origen['viaje_id'];

            $monto_cobrado=($tipo_ajuste==='COBRAR')?max(0,$ajuste_total):0;
            $monto_saldo=($tipo_ajuste==='SALDO')?max(0,$ajuste_total):0;
            $saldo_favor=($tipo_ajuste==='SALDO_FAVOR')?abs(min(0,$ajuste_total)):0;
            $monto_devuelto=($tipo_ajuste==='DEVOLUCION')?abs(min(0,$ajuste_total)):0;
            $hist=array(
                'venta_id'=>(int)$origen['venta_id'],'pasaje_origen_id'=>$origen_id,'pasaje_destino_id'=>$destino_id,
                'viaje_original_id'=>$viaje_original_raiz,'viaje_anterior_id'=>(int)$origen['viaje_id'],'viaje_nuevo_id'=>(int)$destino['viaje_id'],
                'asiento_anterior_id'=>(int)$origen['asiento_id'],'asiento_nuevo_id'=>(int)$destino['asiento_id'],
                'asiento_anterior'=>$origen['asiento_numero'],'asiento_nuevo'=>$destino['asiento_numero'],
                'usuario_id'=>$usuario_id,'reprogramacion_fecha'=>date('Y-m-d'),'reprogramacion_hora'=>date('H:i:s'),'reprogramacion_fechahora'=>date('Y-m-d H:i:s'),'reprogramacion_motivo'=>$motivo,
                'precio_pagado'=>$precio_pagado,'precio_nuevo'=>$precio_nuevo,'diferencia_tarifa'=>$diferencia_tarifa,'penalidad'=>$penalidad,'ajuste_total'=>$ajuste_total,'tipo_ajuste'=>$tipo_ajuste,
                'monto_cobrado'=>$monto_cobrado,'monto_saldo'=>$monto_saldo,'monto_saldo_favor'=>$saldo_favor,'monto_devuelto'=>$monto_devuelto,
                'forma_id_original'=>$forma_original,'forma_id_ajuste'=>$forma_ajuste>0?$forma_ajuste:null,'mantiene_forma_pago'=>$mantiene_forma,
                'estado_pasaje_original'=>(int)$origen['estado_id'],
                'reprogramacion_snapshot'=>json_encode(array('origen'=>$origen,'destino'=>$destino,'venta'=>$venta,'venta_fuente'=>$venta_fuente),JSON_UNESCAPED_UNICODE)
            );
            if(!$this->db->insert('pasaje_reprogramacion',$hist)) throw new Exception('No fue posible registrar la auditoría de reprogramación.');
            $reprogramacion_id=(int)$this->db->insert_id();

            // Liberar asiento anterior sin borrar el historial: queda en pasaje_reprogramacion.
            $limpiar=array('factura_id'=>0,'cliente_id'=>0,'pasaje_nombre'=>'','pasaje_telefono'=>'','pasaje_documento'=>'','estado_id'=>50,'usuario_id'=>0,'venta_id'=>0,'cdi_codigoclasificador'=>0,'pasaje_fecha'=>null,'pasaje_hora'=>null,'pasaje_fechareserva'=>null,'pasaje_fechalimiteres'=>null,'pasaje_horalimiteres'=>null,'pasaje_tieneequipaje'=>0,'pasaje_detalleequipaje'=>null,'pasaje_fechahoraequipaje'=>null,'pasaje_controlabordaje'=>null,'pasaje_bloqueado_hasta'=>null);
            if(!$this->db->where('pasaje_id',$origen_id)->update('pasaje',$limpiar)) throw new Exception('No fue posible liberar el asiento del viaje anterior.');

