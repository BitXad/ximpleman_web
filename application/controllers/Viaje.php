    private function _normalizar_tripulacion_post()
    {
        $conductores = $this->input->post('tripulacion_conductor_id');
        $roles = $this->input->post('tripulacion_rol');
        $conductores = is_array($conductores) ? $conductores : array();
        $roles = is_array($roles) ? $roles : array();
        $principal = ''; $relevo = '';
        foreach ($conductores as $i => $conductor_id) {
            $conductor_id = (int)$conductor_id;
            if ($conductor_id <= 0) continue;
            $rol = strtoupper(trim(isset($roles[$i]) ? $roles[$i] : ''));
            if ($principal === '' && in_array($rol, array('PRINCIPAL','CONDUCTOR'), true)) $principal = (string)$conductor_id;
            if ($relevo === '' && in_array($rol, array('SEGUNDO','RELEVO','SEGUNDO CONDUCTOR'), true)) $relevo = (string)$conductor_id;
        }
        $_POST['conductor_id'] = $principal;
        $_POST['conductor_id2'] = $relevo;
    }

