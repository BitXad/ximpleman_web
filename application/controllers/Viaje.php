            if(!$this->db->where('viaje_id',$viaje_id)->update('viaje',array('estado_id'=>62))) throw new Exception('No fue posible cerrar el viaje.');
            if(!$this->Viaje_model->registrar_historial_estado($viaje_id,56,62,$usuario_id,'CIERRE DE VIAJE'.($motivo!==''?': '.$motivo:''))) throw new Exception('No fue posible registrar la bitácora.');
            if($this->db->trans_status()===false) throw new Exception('La base de datos rechazó el cierre.');
