        $resumen=$this->Viaje_model->get_resumen_cierre((int)$viaje_id);
        if (!$resumen) return $this->output->set_output(json_encode(array('ok'=>false,'mensaje'=>'Viaje no encontrado.')));
        if ((int)$resumen['estado_id']!==56) return $this->output->set_output(json_encode(array('ok'=>false,'mensaje'=>'Solo un viaje en EMBARQUE puede cerrarse.')));
        return $this->output->set_output(json_encode(array('ok'=>true,'resumen'=>$resumen)));
    }

