    /**
     * Datos iniciales para reprogramar un pasaje a otro viaje de la misma ruta.
     */
    public function buscar_viajes_reprogramacion()
    {
        $this->output->set_content_type('application/json');
        $pasaje_id = (int)$this->input->post('pasaje_id');
        $usuario_id = isset($this->session_data['usuario_id']) ? (int)$this->session_data['usuario_id'] : 0;
        if (!$this->Viaje_model->usuario_tiene_rol($usuario_id, 209)) {
            echo json_encode(array('ok'=>false,'mensaje'=>'No tiene permiso para reprogramar pasajes.')); return;
        }
        $actual = $this->db->query(
            "SELECT p.*,a.asiento_numero,a.asiento_descripcion,v.ruta_id,v.viaje_fechasalida,v.viaje_horasalida,v.estado_id AS viaje_estado_id,r.ruta_nombre,
                    COALESCE(vp.forma_id,vg.forma_id) AS forma_id_original,fp.forma_nombre AS forma_nombre_original,COALESCE(vp.venta_total,vg.venta_total) AS venta_total,CASE WHEN vp.venta_id IS NOT NULL THEN 'venta_pasaje' WHEN vg.venta_id IS NOT NULL THEN 'venta' ELSE NULL END AS venta_origen_tabla
             FROM pasaje p
             INNER JOIN asientos a ON a.asiento_id=p.asiento_id
             INNER JOIN viaje v ON v.viaje_id=p.viaje_id
             LEFT JOIN ruta r ON r.ruta_id=v.ruta_id
             LEFT JOIN venta_pasaje vp ON vp.venta_id=p.venta_id
             LEFT JOIN venta vg ON vg.venta_id=p.venta_id AND vp.venta_id IS NULL
             LEFT JOIN forma_pago fp ON fp.forma_id=COALESCE(vp.forma_id,vg.forma_id)
             WHERE p.pasaje_id=? LIMIT 1", array($pasaje_id))->row_array();
        if (!$actual || !in_array((int)$actual['estado_id'], array(52,54), true)) {
            echo json_encode(array('ok'=>false,'mensaje'=>'El pasaje seleccionado no está vendido o reservado.')); return;
        }
        if (!in_array((int)$actual['viaje_estado_id'], array(61,56), true)) {
            echo json_encode(array('ok'=>false,'mensaje'=>'El viaje actual ya no permite reprogramaciones.')); return;
        }
        // Primero obtenemos los viajes candidatos. No dependemos de que sus filas de
        // pasaje ya hayan sido generadas: un viaje puede estar correctamente creado y
        // habilitado, pero todavía no haber cargado su mapa de asientos.
        $candidatos = $this->db->query(
            "SELECT v.viaje_id,v.viaje_fechasalida,v.viaje_horasalida,v.viaje_preciopasaje,v.vehiculo_id,
                    ve.vehiculo_placa,r.ruta_nombre,e.estado_descripcion,v.estado_id
             FROM viaje v
             LEFT JOIN vehiculo ve ON ve.vehiculo_id=v.vehiculo_id
             LEFT JOIN ruta r ON r.ruta_id=v.ruta_id
             LEFT JOIN estado e ON e.estado_id=v.estado_id
             WHERE v.ruta_id=? AND v.viaje_id<>? AND v.estado_id IN (61,56)
               AND TIMESTAMP(v.viaje_fechasalida,v.viaje_horasalida)>=NOW()
             ORDER BY v.viaje_fechasalida,v.viaje_horasalida",
            array((int)$actual['ruta_id'],(int)$actual['viaje_id'])
        )->result_array();

        $viajes = array();
        foreach ($candidatos as $candidato) {
            // Sincroniza/genera únicamente los pasajes que falten para el vehículo.
            // generar_pasajes() no duplica filas existentes.
            if (!empty($candidato['vehiculo_id'])) {
                $this->generar_pasajes((int)$candidato['viaje_id'], (int)$candidato['vehiculo_id']);
            }

            $libres = (int)$this->db->query(
                "SELECT COUNT(*) AS total
                 FROM pasaje
                 WHERE viaje_id=? AND estado_id=50 AND IFNULL(venta_id,0)=0",
                array((int)$candidato['viaje_id'])
            )->row()->total;

            if ($libres > 0) {
                $candidato['asientos_libres'] = $libres;
                $viajes[] = $candidato;
            }
        }

        // Diagnóstico útil para la interfaz: informa si existen viajes futuros de la
        // misma ruta, pero todavía están PROGRAMADOS u otro estado no habilitado.
        $no_habilitados = $this->db->query(
            "SELECT v.viaje_id,v.viaje_fechasalida,v.viaje_horasalida,e.estado_descripcion
             FROM viaje v
             LEFT JOIN estado e ON e.estado_id=v.estado_id
             WHERE v.ruta_id=? AND v.viaje_id<>? AND v.estado_id NOT IN (61,56)
               AND TIMESTAMP(v.viaje_fechasalida,v.viaje_horasalida)>=NOW()
             ORDER BY v.viaje_fechasalida,v.viaje_horasalida",
            array((int)$actual['ruta_id'],(int)$actual['viaje_id'])
        )->result_array();
        $formas = $this->db->query("SELECT forma_id,forma_nombre FROM forma_pago WHERE IFNULL(estado_id,1)=1 ORDER BY forma_nombre")->result_array();
        echo json_encode(array('ok'=>true,'actual'=>$actual,'viajes'=>$viajes,'viajes_no_habilitados'=>$no_habilitados,'formas_pago'=>$formas));
    }

