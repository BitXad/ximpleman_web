    public function confirmar_abordaje()
    {
        $this->output->set_content_type('application/json'); $uid=(int)$this->session_data['usuario_id'];
        if (!$this->Viaje_model->usuario_tiene_rol($uid,211)) return $this->output->set_output(json_encode(array('ok'=>false,'mensaje'=>'No tiene permiso para control de abordaje.')));
        $pasaje_id=(int)$this->input->post('pasaje_id'); $viaje_id=(int)$this->input->post('viaje_id'); $terminal=trim((string)$this->input->post('terminal',true));
        if($terminal==='') $terminal='TERMINAL'; if(strlen($terminal)>100)$terminal=substr($terminal,0,100);
        $this->db->trans_begin();
        try {
            $viaje=$this->db->query("SELECT viaje_id,estado_id FROM viaje WHERE viaje_id=? FOR UPDATE",array($viaje_id))->row_array();
            if(!$viaje || (int)$viaje['estado_id']!==56) throw new Exception('El abordaje solo puede registrarse cuando el viaje está en EMBARQUE.');
            $p=$this->db->query("SELECT p.*,a.asiento_numero,r.ruta_nombre FROM pasaje p INNER JOIN asientos a ON a.asiento_id=p.asiento_id INNER JOIN viaje v ON v.viaje_id=p.viaje_id LEFT JOIN ruta r ON r.ruta_id=v.ruta_id WHERE p.pasaje_id=? AND p.viaje_id=? FOR UPDATE",array($pasaje_id,$viaje_id))->row_array();
            if(!$p) throw new Exception('Pasaje no encontrado para este viaje.');
            if((int)$p['estado_id']!==54) throw new Exception('El pasaje no está vendido/habilitado para abordar.');
            $ya=$this->db->query("SELECT ab.*,u.usuario_nombre FROM pasaje_abordaje ab LEFT JOIN usuario u ON u.usuario_id=ab.usuario_id WHERE ab.pasaje_id=? AND ab.abordaje_estado='A BORDO' LIMIT 1 FOR UPDATE",array($pasaje_id))->row_array();
            if($ya){
                $this->db->insert('pasaje_abordaje_intento',array('pasaje_id'=>$pasaje_id,'viaje_id'=>$viaje_id,'usuario_id'=>$uid,'intento_fecha'=>date('Y-m-d'),'intento_hora'=>date('H:i:s'),'intento_terminal'=>$terminal,'intento_resultado'=>'DUPLICADO'));
                $this->db->trans_commit();
                return $this->output->set_output(json_encode(array('ok'=>false,'codigo'=>'YA_REGISTRADO','mensaje'=>'PASAJERO YA REGISTRADO – '.substr($ya['abordaje_hora'],0,5),'hora'=>$ya['abordaje_hora'],'fecha'=>$ya['abordaje_fecha'],'terminal'=>$ya['abordaje_terminal'],'controlador'=>isset($ya['usuario_nombre'])?$ya['usuario_nombre']:'')));
            }
            $this->db->insert('pasaje_abordaje',array('pasaje_id'=>$pasaje_id,'viaje_id'=>$viaje_id,'usuario_id'=>$uid,'abordaje_fecha'=>date('Y-m-d'),'abordaje_hora'=>date('H:i:s'),'abordaje_terminal'=>$terminal,'abordaje_estado'=>'A BORDO'));
            if(!$this->db->affected_rows()) throw new Exception('No se pudo registrar el abordaje.');
            $this->db->where('pasaje_id',$pasaje_id)->update('pasaje',array('pasaje_controlabordaje'=>'A BORDO'));
            $this->db->insert('pasaje_abordaje_intento',array('pasaje_id'=>$pasaje_id,'viaje_id'=>$viaje_id,'usuario_id'=>$uid,'intento_fecha'=>date('Y-m-d'),'intento_hora'=>date('H:i:s'),'intento_terminal'=>$terminal,'intento_resultado'=>'ACEPTADO'));
            if($this->db->trans_status()===false) throw new Exception('Error de base de datos durante el abordaje.');
            $this->db->trans_commit();
            $this->load->model('Bitacora_transporte_model');
            $this->Bitacora_transporte_model->registrar('ABORDAJE','PASAJE',$pasaje_id,array('pasaje_controlabordaje'=>$p['pasaje_controlabordaje']??null),array('pasaje_controlabordaje'=>'A BORDO','terminal'=>$terminal),array('pasaje_id'=>$pasaje_id,'viaje_id'=>$viaje_id,'venta_id'=>(int)$p['venta_id'],'usuario_id'=>$uid));
            return $this->output->set_output(json_encode(array('ok'=>true,'codigo'=>'HABILITADO','mensaje'=>'PASAJERO HABILITADO','pasajero'=>$p['pasaje_nombre'],'asiento'=>$p['asiento_numero'],'ruta'=>$p['ruta_nombre'],'hora'=>date('H:i:s'),'resumen'=>$this->Viaje_model->get_resumen_abordaje($viaje_id))));
        } catch(Exception $e){ $this->db->trans_rollback(); return $this->output->set_output(json_encode(array('ok'=>false,'mensaje'=>$e->getMessage()))); }
    }

