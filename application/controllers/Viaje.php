            if(!$this->db->where('pasaje_id',$destino_id)->update('pasaje',$mover)) throw new Exception('No fue posible asignar el asiento del nuevo viaje.');

            // Si toda la venta quedó en un único viaje, actualizar la referencia operativa de cabecera.
            // El viaje original permanece siempre en pasaje_reprogramacion.viaje_original_id.
            $viajes_venta=$this->db->query("SELECT DISTINCT viaje_id FROM pasaje WHERE venta_id=? AND estado_id IN (52,54)",array((int)$origen['venta_id']))->result_array();
