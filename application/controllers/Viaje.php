    /**
     * Fuerza la vista completa del manifiesto, independientemente del tipo de impresora.
     * Útil desde el formato boucher para consulta en pantalla.
     */
    public function manifiesto_completo($viaje_id = null)
    {
        $uid=isset($this->session_data['usuario_id'])?(int)$this->session_data['usuario_id']:0;
        if(!$this->Viaje_model->usuario_tiene_rol($uid,220)){ show_error('No tiene permiso para generar reportes de Transporte.',403,'Acceso denegado'); return; }
        $viaje_id = (int)$viaje_id;
        $cabecera = $this->Viaje_model->get_manifiesto_cabecera($viaje_id);
        if (!$cabecera) {
            show_404();
        }

        $data = array();
        $data['sistema'] = $this->sistema;
        $data['parametro'] = $this->parametros;
        $data['empresa'] = $this->Empresa_model->get_empresa(1);
        $data['cabecera'] = $cabecera;
        $data['pasajeros'] = $this->Viaje_model->get_manifiesto_pasajeros($viaje_id);
        $data['modo_pdf'] = false;
        $data['_view'] = 'viaje/manifiesto';
        $this->load->view('layouts/main', $data);
    }

    /** Genera el manifiesto en PDF A4 horizontal. */
    public function manifiesto_pdf($viaje_id = null)
    {
        $uid=isset($this->session_data['usuario_id'])?(int)$this->session_data['usuario_id']:0;
        if(!$this->Viaje_model->usuario_tiene_rol($uid,220)){ show_error('No tiene permiso para generar reportes de Transporte.',403,'Acceso denegado'); return; }
        $viaje_id = (int)$viaje_id;
        $cabecera = $this->Viaje_model->get_manifiesto_cabecera($viaje_id);
        if (!$cabecera) {
            show_404();
        }

        $data = array(
            'empresa' => $this->Empresa_model->get_empresa(1),
            'cabecera' => $cabecera,
            'pasajeros' => $this->Viaje_model->get_manifiesto_pasajeros($viaje_id),
            'modo_pdf' => true
        );

        $html = $this->load->view('viaje/manifiesto', $data, true);
        $options = new Options();
        $options->set('isRemoteEnabled', true);
        $options->set('isHtml5ParserEnabled', true);
        $dompdf = new Dompdf($options);
        $dompdf->loadHtml($html, 'UTF-8');
        $dompdf->setPaper('A4', 'landscape');
        $dompdf->render();
        $dompdf->stream('manifiesto_viaje_'.$viaje_id.'.pdf', array('Attachment' => false));
        exit;
    }

